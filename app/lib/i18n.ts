export type Language = "en" | "fr" | "de" | "es";

export const supportedLanguages: Language[] = ["en", "fr", "de", "es"];

export function formatPrice(amount: number, lang: Language): string {
  switch (lang) {
    case "fr":
      return `${amount}€`;
    case "de":
      return `${amount}€`;
    case "es":
      return `${amount}€`;
    case "en":
    default:
      return `$${amount}`;
  }
}

export function getCurrency(lang: Language): string {
  switch (lang) {
    case "fr":
    case "de":
    case "es":
      return "EUR";
    case "en":
    default:
      return "USD";
  }
}

